// Builds brief/inst/navdata.js, the US navaid and ILS data for the Flight
// Instruments page, from the FAA NASR snapshots in the @squawk/navaid-data
// and @squawk/airport-data npm packages (FAA data is public domain; the
// packages are MIT).
//
//   npm pack @squawk/navaid-data @squawk/airport-data   (in an empty folder)
//   tar xzf squawk-navaid-data-*.tgz && mv package navaid
//   tar xzf squawk-airport-data-*.tgz && mv package airport
//   node tools/build-navdata.mjs <that folder>/navaid/data/navaids.json.gz <that folder>/airport/data/airports.json.gz
//
// The output is a classic script (not JSON) so the page still works when
// opened straight from disk, where fetch() is blocked.
import { readFileSync, writeFileSync } from 'node:fs';
import { gunzipSync } from 'node:zlib';
import { fileURLToPath } from 'node:url';

const [navPath, aptPath] = process.argv.slice(2);
if (!navPath || !aptPath) { console.error('usage: node tools/build-navdata.mjs navaids.json.gz airports.json.gz'); process.exit(1); }
const load = p => JSON.parse(gunzipSync(readFileSync(p)).toString('utf8'));
const navSrc = load(navPath), aptSrc = load(aptPath);

const r5 = v => Math.round(v * 1e5) / 1e5;
const r0 = v => (v == null ? null : Math.round(v));
const signedVar = (deg, dir) => (deg == null ? null : dir === 'W' ? -deg : deg);   // east positive

// ---------- navaids ----------
// [id, type, name, lat, lon, elevFt, MHz, kHz, tacanChannel, varE, vorClass, dmeClass, ndbClass]
const KEEP = new Set(['VOR', 'VOR/DME', 'VORTAC', 'TACAN', 'DME', 'NDB', 'NDB/DME']);
const nav = [];
for (const r of navSrc.records) {
  if (r.country !== 'US' || !KEEP.has(r.type)) continue;
  nav.push([r.identifier, r.type, r.name, r5(r.lat), r5(r.lon), r0(r.elevationFt) ?? 0,
    r.frequencyMhz ?? null, r.frequencyKhz ?? null, r.tacanChannel ?? null,
    signedVar(r.magneticVariationDeg, r.magneticVariationDirection) ?? null,
    r.navaidClass ?? null, r.dmeServiceVolume ?? null, r.ndbClass ?? null]);
}
nav.sort((a, b) => a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0);

// ---------- airports with an ILS, LOC, LDA or SDF ----------
// [faaId, icao, name, lat, lon, elevFt, varE,
//   runways: [[id, latA, lonA, elevA, latB, lonB, elevB, widthFt]],
//   ils: [[runwayEnd, ident, system, MHz, magCourse, gsAngle|null, tchFt, displacedFt, dmeChannel|null]]]
const apt = [];
for (const a of aptSrc.records) {
  if (a.country !== 'US' || a.status !== 'OPEN') continue;
  const rw = [], ils = [];
  for (const w of a.runways || []) {
    const [A, B] = w.ends || [];
    if (!A || !B || A.lat == null || B.lat == null) continue;
    rw.push([w.id, r5(A.lat), r5(A.lon), r0(A.elevationFt ?? a.elevationFt), r5(B.lat), r5(B.lon), r0(B.elevationFt ?? a.elevationFt), r0(w.widthFt) || 75]);
    for (const e of [A, B]) {
      const i = e.ils;
      if (!i || !i.localizerFrequencyMhz) continue;
      ils.push([e.id, (i.identifier || '').replace(/^I-/, 'I'), i.systemType, i.localizerFrequencyMhz, Math.round(i.localizerMagneticCourseDeg * 10) / 10,
        i.glideSlopeAngleDeg || null, r0(e.thresholdCrossingHeightFt) || 50, r0(e.displacedThresholdFt) || 0, i.dmeChannel || null]);
    }
  }
  if (!ils.length) continue;
  apt.push([a.faaId, a.icao || null, a.name, r5(a.lat), r5(a.lon), r0(a.elevationFt) ?? 0,
    signedVar(a.magneticVariationDeg, a.magneticVariationDirection) ?? 0, rw, ils]);
}
apt.sort((a, b) => (a[1] || a[0]) < (b[1] || b[0]) ? -1 : 1);

const out = {
  cycle: navSrc.meta.nasrCycleDate,
  source: 'FAA NASR via @squawk/navaid-data ' + navSrc.meta.nasrCycleDate + ' and @squawk/airport-data ' + aptSrc.meta.nasrCycleDate,
  nav, apt,
};
const dest = fileURLToPath(new URL('../brief/inst/navdata.js', import.meta.url));
writeFileSync(dest, '// Generated by tools/build-navdata.mjs from FAA NASR data. Training use only, not for navigation.\n' +
  'window.FI = window.FI || {};\nFI.NAVDATA = ' + JSON.stringify(out) + ';\n');
console.log(`${nav.length} navaids, ${apt.length} airports, ${apt.reduce((n, a) => n + a[8].length, 0)} approaches -> ${dest}`);
